    obj = bpy.context.object
    obj.name = rec['name']
    obj.data.name = rec['name'] + '_mesh'
    apply_exact_dimensions_before_rotation(obj, dims)
    set_exact_transform(obj, rec)
    assign_and_shade(obj, mat, smooth=True)
    return obj


